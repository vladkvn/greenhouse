// rover-01 — общий моторный модуль.
// Один и тот же код управления моторами используют ОБЕ сборки:
//   - microros (приём /cmd_vel по ROS2)
//   - webtest  (управление из браузера)
// Благодаря этому веб-команды действуют на робота РОВНО так же, как ROS-команды,
// включая watchdog. Это и есть «как будто сигнал пришёл по ROS».

#pragma once

// Инициализация пинов и ШИМ. Сразу переводит моторы в безопасный стоп.
void motorsBegin();

// Задать цель в терминах Twist: линейная (м/с) и угловая (рад/с) скорости.
// Внутри раскладывает на борта (skid-steer) и «пинает» watchdog.
void motorsSetTarget(float linear_x, float angular_z);

// Управляющий тик: watchdog + slew + применение к моторам.
// Вызывать периодически, раз в CONTROL_PERIOD_MS.
void motorsTick();

// Немедленный жёсткий стоп и сброс целей.
void motorsStopHard();

// Миллисекунды с момента последней команды (для диагностики/статуса).
unsigned long motorsMsSinceLastCmd();
