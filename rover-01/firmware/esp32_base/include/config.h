// rover-01 — конфигурация прошивки ESP32
// Всё, что нужно подстраивать под железо, собрано здесь.
// Разводка: 1× L298N, борт = канал (левые 2 мотора → канал A, правые 2 → канал B).

#pragma once

// ───────────────────────── Распиновка L298N ─────────────────────────
// Проверь GPIO под свою плату ESP32. Не используй input-only пины (34-39) для выходов.
// Канал A = ЛЕВЫЙ борт, Канал B = ПРАВЫЙ борт.
#define PIN_IN1 25  // L298N IN1  (левый борт, направление)
#define PIN_IN2 26  // L298N IN2  (левый борт, направление)
#define PIN_ENA 27  // L298N ENA  (левый борт, ШИМ скорость)

#define PIN_IN3 14  // L298N IN3  (правый борт, направление)
#define PIN_IN4 12  // L298N IN4  (правый борт, направление)
#define PIN_ENB 13  // L298N ENB  (правый борт, ШИМ скорость)

// ───────────────────────── ШИМ (LEDC) ─────────────────────────
#define PWM_FREQ_HZ   1000  // частота ШИМ моторов
#define PWM_RES_BITS  8     // 8 бит → диапазон 0..255
#define PWM_MAX       255
#define LEDC_CH_LEFT  0     // канал LEDC для левого борта
#define LEDC_CH_RIGHT 1     // канал LEDC для правого борта

// Мёртвая зона: минимальный ШИМ, при котором мотор реально начинает крутиться.
// Определяется ЭКСПЕРИМЕНТАЛЬНО на этапе 0 (см. docs/05-test-plan.md). Подбери под свои моторы.
#define PWM_DEADZONE  60

// ───────────────────────── Кинематика (skid-steer) ─────────────────────────
#define WHEEL_BASE_M      0.20f  // колея: расстояние между бортами, метры. ИЗМЕРЬ.
#define MAX_WHEEL_SPEED   0.5f   // м/с, которой соответствует ШИМ=255 (грубая оценка, open-loop)

// ───────────────────────── Безопасность / поведение ─────────────────────────
#define CMD_TIMEOUT_MS    300    // нет /cmd_vel дольше этого → стоп (watchdog)
#define CONTROL_PERIOD_MS 20     // период управляющего цикла (таймер)
// Slew-rate: максимальное изменение нормированной скорости (-1..1) за один цикл управления.
// Меньше → плавнее пуск, бережёт L298N и питание. 0.05 ≈ полный разгон за ~0.4 c.
#define SLEW_PER_TICK     0.05f

// ───────────────────────── ROS2 имена ─────────────────────────
#define NODE_NAME       "rover_base"
#define TOPIC_CMD_VEL   "cmd_vel"
#define TOPIC_HEARTBEAT "rover/heartbeat"  // Int32-счётчик, растёт пока нода жива

// Период публикации heartbeat (в тиках управляющего цикла). 25 * 20мс = 500мс.
#define HEARTBEAT_EVERY_TICKS 25
